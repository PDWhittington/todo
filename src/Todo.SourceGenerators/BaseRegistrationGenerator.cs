using System.Collections.Generic;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Todo.SourceGenerators;

public abstract class BaseRegistrationGenerator : IIncrementalGenerator
{
    private static bool NodePredicate(SyntaxNode syntaxNode, CancellationToken cancellationToken)
        => syntaxNode is ClassDeclarationSyntax;

    private RegistrationInfo? Transform(GeneratorSyntaxContext context, 
        CancellationToken cancellationToken)
    {
        var classDecl = (ClassDeclarationSyntax)context.Node;
        var semanticModel = context.SemanticModel;

        if (semanticModel.GetDeclaredSymbol(classDecl, cancellationToken)
            is not INamedTypeSymbol classSymbol)
            return null;

        // Must be a concrete class (not abstract)
        if (classSymbol.IsAbstract || classSymbol.IsGenericType)
            return null;

        var isRequired = classSymbol
            .AllInterfaces
            .Any(InterfaceIsPrimaryInterface);

        if (!isRequired) return null;

        var interfaces = GetAdditionalInterfacesForRegistration(classSymbol)
            .ToArray();

        return interfaces.Length != 0 
            ? new RegistrationInfo(interfaces, classSymbol) 
            : null;
    }

    private string OutputFileName() => $"{OutputClassName()}.g.cs";

    protected abstract string OutputClassName();

    protected abstract string OutputMethodName();

    protected abstract string[] OutputUsings();

    protected abstract bool InterfaceIsPrimaryInterface(INamedTypeSymbol interfaceSymbol);

    protected abstract bool InterfaceIsRequired(INamedTypeSymbol interfaceSymbol);

    public virtual void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Find all classes that implement ICommandFactory<CommandBase>
        var registrationPairs = context
            .SyntaxProvider.CreateSyntaxProvider(
                predicate: NodePredicate,
                transform: Transform)
            .Where(x => x is not null)
            .Collect(); 

        // Generate one file from all factories
        context.RegisterSourceOutput(
            registrationPairs,
            (spc, rps) =>
            {
                var source = GenerateRegistrationCode(rps!);
                spc.AddSource(OutputFileName(),
                    SourceText.From(source, Encoding.UTF8));
            });
    }

    private string GenerateRegistrationCode(ImmutableArray<RegistrationInfo> registrationPairs)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");

        foreach (var @using in OutputUsings())
        {
            sb.AppendLine($"using {@using};");
        }

        sb.AppendLine();
        sb.AppendLine("namespace Todo;"); 
        sb.AppendLine();
        sb.AppendLine($"public static class {OutputClassName()}");
        sb.AppendLine("{");
        sb.AppendLine(
            $"    public static IServiceCollection {OutputMethodName()}(this IServiceCollection services)"
        );
        sb.AppendLine("    {");
        sb.AppendLine("       return services");

        var registrationPairsOrdered = registrationPairs
            .OrderBy(x => x.Implementation.Name);

        foreach (var executorPair in registrationPairsOrdered)
        {
            var displayStrings = executorPair.Interfaces
                .Select(x => x.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .Select(x => $"typeof({x})");

            var interfaceArrayStr = $"new Type [] {{{string.Join(",", displayStrings)}}}";

            var implementationType = executorPair.Implementation.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var implementationTypeWithTypeOf = $"typeof({implementationType})";

            sb.AppendLine($"        .RegisterSeveralInterfaces({interfaceArrayStr}, {implementationTypeWithTypeOf})");
        }

        sb.AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Hook to return additional interfaces that the implementation should be registered against.
    /// The default implementation infers registrations for covariant (out) type parameters:
    /// if a primary interface is declared as e.g. IFoo&lt;out T&gt; where T : SomeBase,
    /// then an implementation of IFoo&lt;Specific&gt; will also be registered against IFoo&lt;SomeBase&gt;.
    /// </summary>
    private IEnumerable<INamedTypeSymbol> GetAdditionalInterfacesForRegistration(
        INamedTypeSymbol classSymbol)
    {
        var interfacesReturned = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);

        var interfaces = classSymbol
            .AllInterfaces
            .Where(InterfaceIsRequired)
            .ToArray();

        foreach (var @interface in interfaces)
        {
            if (interfacesReturned.Add(@interface))
            {
                yield return @interface;    
            }
        }

        foreach (var iface in interfaces)
        {
            if (iface.TypeArguments.Length == 0) continue;

            var originalDefinition = iface.OriginalDefinition;

            for (var i = 0; i < originalDefinition.TypeParameters.Length; i++)
            {
                var typeParam = originalDefinition.TypeParameters[i];

                if (typeParam.Variance != VarianceKind.Out) continue;

                // For 'out T', we can safely register against the interface using the constraint type(s)
                // as the type argument (the common supertype for all possible T).
                foreach (var constraint in typeParam.ConstraintTypes.OfType<INamedTypeSymbol>())
                {
                        // Build the type arguments array with this slot replaced by the constraint
                        var newTypeArgs = iface.TypeArguments
                            .Select((arg, idx) => idx == i ? constraint : arg)
                            .ToArray();

                        var constructed = originalDefinition.Construct(newTypeArgs);

                        if (interfacesReturned.Add(constructed))
                        {
                            yield return constructed;
                        }
                }
            }
        }
    }
}